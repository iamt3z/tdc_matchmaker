import type { ISODateTime } from "./common";

/**
 * Individual compatibility factors that contribute to a match score.
 */
export interface MatchScoreBreakdown {
  mutualPreferences: number;
  familyExpectations: number;
  lifestyle: number;
  careerAndEducation: number;
  locationAndRelocation: number;
  language: number;
}

/**
 * Explains why a candidate received their compatibility score.
 */
export interface MatchExplanation {
  summary: string;

  /**
   * Positive compatibility observations supported by profile data.
   */
  strengths: string[];

  /**
   * Relevant mismatches or unknown information.
   */
  considerations: string[];

  /**
   * Identifies how the explanation was generated.
   */
  generatedBy: "RULES" | "LLM";
}

/**
 * Lifecycle of a suggested match.
 */
export type MatchStatus =
  | "SUGGESTED"
  | "SHORTLISTED"
  | "SENT"
  | "ACCEPTED"
  | "DECLINED"
  | "WITHDRAWN";

/**
 * Records a match suggestion between two customers.
 *
 * The compatibility score is generated by the matching engine.
 * The LLM must not independently override eligibility rules.
 */
export interface Match {
  id: string;

  customerId: string;
  candidateCustomerId: string;

  score: number;
  scoreBreakdown: MatchScoreBreakdown;

  explanation: MatchExplanation;

  status: MatchStatus;

  /**
   * Tracks the matchmaker who generated or managed the suggestion.
   */
  matchmakerId: string;

  createdAt: ISODateTime;
  updatedAt: ISODateTime;

  sentAt?: ISODateTime;
  feedback?: string;
}

/**
 * Data returned to the frontend when requesting ranked candidates.
 */
export interface MatchSuggestion {
  match: Match;

  /**
   * A minimal candidate profile suitable for a match card.
   */
  candidate: {
    id: string;
    firstName: string;
    age: number;
    city: string;
    heightCm?: number;
    degree?: string;
    designation?: string;
    introduction?: string;
  };
}

/**
 * Request parameters for generating matches.
 */
export interface GenerateMatchesInput {
  customerId: string;

  /**
   * Maximum number of suggestions to return.
   */
  limit?: number;

  /**
   * Whether candidates with incomplete profiles can be considered.
   * Verified profiles should be preferred for the assignment.
   */
  includeUnverified?: boolean;
}

/**
 * Result of a Send Match action.
 *
 * The initial implementation simulates sending an introduction.
 * It does not imply that a real email was delivered.
 */
export interface SendMatchResult {
  matchId: string;
  status: "SENT";
  simulated: true;
  message: string;
  sentAt: ISODateTime;
}